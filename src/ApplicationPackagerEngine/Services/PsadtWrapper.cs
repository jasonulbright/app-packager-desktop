namespace ApplicationPackagerEngine.Services;

/// <summary>
/// Generates PowerShell App Deployment Toolkit (PSADT) wrappers for application deployment.
/// Creates Deploy-Application.ps1 with pre/post-install logic, user interaction support,
/// and PSADT best practices.
///
/// IMPORTANT: Creates a SECOND separate CM Application with [Interactive] suffix,
/// NOT a second deployment type on the same app. A user-interactive DT poisons TS
/// compatibility for the entire app in MECM.
/// - Silent app = Required/TS deployments
/// - Interactive app = Available/Software Center self-service
/// </summary>
public sealed class PsadtWrapper
{
    /// <summary>
    /// Generates PSADT Deploy-Application.ps1 from a stage manifest.
    /// Output goes to a separate content folder (not the same as the silent install content).
    /// </summary>
    public void Generate(string outputPath, Models.StageManifest manifest, PsadtOptions? options = null)
    {
        options ??= new PsadtOptions();
        Directory.CreateDirectory(outputPath);

        var installerFile = manifest.InstallerFile;
        var installArgs = manifest.InstallArgs;
        var uninstallArgs = manifest.UninstallArgs;
        var appName = manifest.AppName;
        var publisher = manifest.Publisher;
        var version = manifest.SoftwareVersion;
        var runningProcesses = manifest.RunningProcess ?? [];

        var script = GenerateDeployScript(
            appName, publisher, version, installerFile,
            installArgs, uninstallArgs, runningProcesses, options);

        File.WriteAllText(Path.Combine(outputPath, "Deploy-Application.ps1"), script);
    }

    private static string GenerateDeployScript(
        string appName, string publisher, string version, string installerFile,
        string installArgs, string uninstallArgs, string[] runningProcesses,
        PsadtOptions options)
    {
        var processCloseList = runningProcesses.Length > 0
            ? string.Join(", ", runningProcesses.Select(p => $"'{p}'"))
            : "'none'";

        var installCommand = installerFile.EndsWith(".msi", StringComparison.OrdinalIgnoreCase)
            ? $"Execute-MSI -Action Install -Path '$dirFiles\\{installerFile}' -Parameters '{installArgs}'"
            : $"Execute-Process -Path '$dirFiles\\{installerFile}' -Parameters '{installArgs}' -WaitForMSIExec";

        var uninstallCommand = installerFile.EndsWith(".msi", StringComparison.OrdinalIgnoreCase)
            ? $"Execute-MSI -Action Uninstall -Path '$dirFiles\\{installerFile}' -Parameters '{uninstallArgs}'"
            : $"Execute-Process -Path '$dirFiles\\{installerFile}' -Parameters '{uninstallArgs}'";

        return $$"""
            <#
            .SYNOPSIS
                PSADT wrapper for {{appName}}
                Generated by SRL Packr
            #>
            [CmdletBinding()]
            Param (
                [Parameter(Mandatory=$false)]
                [ValidateSet('Install','Uninstall','Repair')]
                [string]$DeploymentType = 'Install',
                [Parameter(Mandatory=$false)]
                [ValidateSet('Interactive','Silent','NonInteractive')]
                [string]$DeployMode = 'Interactive',
                [Parameter(Mandatory=$false)]
                [switch]$AllowRebootPassThru = $false,
                [Parameter(Mandatory=$false)]
                [switch]$TerminalServerMode = $false,
                [Parameter(Mandatory=$false)]
                [switch]$DisableLogging = $false
            )

            Try {
                ## Set the script execution policy for this process
                Try { Set-ExecutionPolicy -ExecutionPolicy 'ByPass' -Scope 'Process' -Force -ErrorAction 'Stop' } Catch {}

                ##*===============================================
                ##* VARIABLE DECLARATION
                ##*===============================================
                [string]$appVendor = '{{publisher}}'
                [string]$appName = '{{appName}}'
                [string]$appVersion = '{{version}}'
                [string]$appArch = 'x64'
                [string]$appLang = 'EN'
                [string]$appRevision = '01'
                [string]$appScriptVersion = '1.0.0'
                [string]$appScriptDate = '{{DateTimeOffset.Now:yyyy-MM-dd}}'
                [string]$appScriptAuthor = 'SRL Packr'
                ##*===============================================
                ##* Do not modify section below
                ##*===============================================
                If (Test-Path -LiteralPath 'variable:HostInvocation') { $InvocationInfo = $HostInvocation } Else { $InvocationInfo = $MyInvocation }
                [string]$scriptDirectory = Split-Path -Path $InvocationInfo.MyCommand.Definition -Parent
                Try {
                    [string]$moduleAppDeployToolkitMain = "$scriptDirectory\AppDeployToolkit\AppDeployToolkitMain.ps1"
                    If (-not (Test-Path -LiteralPath $moduleAppDeployToolkitMain -PathType 'Leaf')) { Throw "Module does not exist at the expected path [$moduleAppDeployToolkitMain]." }
                    . $moduleAppDeployToolkitMain
                }
                Catch {
                    [int32]$mainExitCode = 60008
                    Write-Error -Message "Module [$moduleAppDeployToolkitMain] failed to load: `n$($_.Exception.Message)`n `n$($_.InvocationInfo.PositionMessage)" -ErrorAction 'Continue'
                    If ($mainExitCode -eq 0){ [int32]$mainExitCode = 60001 }
                    Exit $mainExitCode
                }

                ##*===============================================
                ##* PRE-INSTALLATION
                ##*===============================================
                [string]$installPhase = 'Pre-Installation'
                Show-InstallationWelcome -CloseApps {{processCloseList}} -CheckDiskSpace -PersistPrompt

                ##*===============================================
                ##* INSTALLATION
                ##*===============================================
                [string]$installPhase = 'Installation'
                If ($deploymentType -ieq 'Install') {
                    {{installCommand}}
                }
                ElseIf ($deploymentType -ieq 'Uninstall') {
                    {{uninstallCommand}}
                }

                ##*===============================================
                ##* POST-INSTALLATION
                ##*===============================================
                [string]$installPhase = 'Post-Installation'

                ##*===============================================
                ##* END SCRIPT BODY
                ##*===============================================
                Exit-Script -ExitCode $mainExitCode
            }
            Catch {
                [int32]$mainExitCode = 60001
                [string]$mainErrorMessage = "$(Resolve-Error)"
                Write-Log -Message $mainErrorMessage -Severity 3 -Source $deployAppScriptFriendlyName
                Show-DialogBox -Text $mainErrorMessage -Icon 'Stop'
                Exit-Script -ExitCode $mainExitCode
            }
            """;
    }
}

public sealed class PsadtOptions
{
    /// <summary>Show balloon notification to user during install</summary>
    public bool ShowBalloonNotification { get; set; } = true;
    /// <summary>Allow user to defer installation</summary>
    public bool AllowDefer { get; set; } = false;
    /// <summary>Maximum number of deferrals allowed</summary>
    public int MaxDeferrals { get; set; } = 3;
}
