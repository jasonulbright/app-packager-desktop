<#
.SYNOPSIS
    Compiles the per-user installer from a published stage.

.DESCRIPTION
    Writes the uninstaller's file list from the stage contents (one Delete per
    file, one RMDir per folder, deepest first), then compiles
    installer\AppPackagerDesktop.nsi with makensis into
    <OutputDir>\AppPackagerDesktop-Setup-<version>.exe. The stage is packaged
    as found, so files signed before this step keep their signatures inside
    the installer. The version comes from <Version> in the UI csproj.

.PARAMETER StageDir
    Published folder holding ApplicationPackagerUI.exe, AppPackagerBuild.exe and Definitions\.

.PARAMETER OutputDir
    Folder that receives the installer. The generated include is written to
    <OutputDir>\installer-generated.

.PARAMETER MakeNsis
    makensis.exe to use. Found on PATH or under the default NSIS folder when omitted.

.PARAMETER UninstallerOnly
    Pass 1 of 2. Builds the uninstaller on its own into <OutputDir>\uninstaller\Uninstall.exe and stops. The release
    signs that file, then runs this script again with -SignedUninstaller. Windows Defender removes an unsigned
    Uninstall.exe that the installer writes at install time.

.PARAMETER SignedUninstaller
    Pass 2 of 2. The signed Uninstall.exe from pass 1. The installer carries this file instead of writing its own.
    Without it (a local build) the installer writes an unsigned uninstaller and this script warns.

.OUTPUTS
    The installer path, or with -UninstallerOnly the uninstaller path.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$StageDir,
    [Parameter(Mandatory)][string]$OutputDir,
    [string]$MakeNsis,
    [switch]$UninstallerOnly,
    [string]$SignedUninstaller
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$repoRoot = Split-Path -Parent $PSScriptRoot
$projectPath = Join-Path $repoRoot 'src\ApplicationPackagerUI\ApplicationPackagerUI.csproj'
$script = Join-Path $repoRoot 'installer\AppPackagerDesktop.nsi'
$icon = Join-Path $repoRoot 'src\ApplicationPackagerUI\app.ico'
$runtimeScript = Join-Path $repoRoot 'installer\Install-DesktopRuntime.ps1'
$runtimeProps = Join-Path $repoRoot 'src\DesktopRuntime.props'
foreach ($required in @($projectPath, $script, $icon, $runtimeScript, $runtimeProps)) {
    if (-not (Test-Path -LiteralPath $required)) { throw "Missing: $required" }
}
$StageDir = (Resolve-Path -LiteralPath $StageDir).Path
foreach ($executable in @('ApplicationPackagerUI.exe', 'AppPackagerBuild.exe')) {
    if (-not (Test-Path -LiteralPath (Join-Path $StageDir $executable))) {
        throw "No $executable under $StageDir; publish first."
    }
}

if (-not $MakeNsis) {
    $command = Get-Command makensis.exe -ErrorAction SilentlyContinue
    if ($command) { $MakeNsis = $command.Source }
    else {
        $MakeNsis = @("${env:ProgramFiles(x86)}\NSIS\makensis.exe", "${env:ProgramFiles}\NSIS\makensis.exe") |
            Where-Object { $_ -and (Test-Path -LiteralPath $_) } | Select-Object -First 1
    }
}
if (-not $MakeNsis -or -not (Test-Path -LiteralPath $MakeNsis)) {
    throw 'makensis.exe not found; install NSIS or pass -MakeNsis.'
}

[xml]$projectXml = Get-Content -LiteralPath $projectPath
$version = (($projectXml.Project.PropertyGroup.Version | Where-Object { $_ }) | Select-Object -First 1)
if (-not $version) { throw "No <Version> element in $projectPath." }
$version = "$version".Trim()
# The lowest .NET Windows Desktop Runtime the application needs; one value for the runtime configuration,
# the installer check and the script default.
[xml]$propsXml = Get-Content -LiteralPath $runtimeProps
$runtimeMin = (($propsXml.Project.PropertyGroup.DesktopRuntimeMinimum | Where-Object { $_ }) | Select-Object -First 1)
if (-not $runtimeMin -or "$runtimeMin".Trim() -notmatch '^\d+\.\d+\.\d+$') { throw "No usable <DesktopRuntimeMinimum> in $runtimeProps." }
$runtimeMin = "$runtimeMin".Trim()
# The version resource takes four numeric parts; a pre-release suffix is
# dropped there and kept in ProductVersion and DisplayVersion.
$numeric = ($version -split '-', 2)[0]
$parts = @($numeric -split '\.' | ForEach-Object { [int]$_ })
while ($parts.Count -lt 4) { $parts += 0 }
$version4 = ($parts[0..3] -join '.')

New-Item -ItemType Directory -Path $OutputDir -Force | Out-Null
$OutputDir = (Resolve-Path -LiteralPath $OutputDir).Path
$generatedDir = Join-Path $OutputDir 'installer-generated'
New-Item -ItemType Directory -Path $generatedDir -Force | Out-Null
$outFile = Join-Path $OutputDir "AppPackagerDesktop-Setup-$version.exe"
if (Test-Path -LiteralPath $outFile) { Remove-Item -LiteralPath $outFile -Force }

# Uninstall list: files first, then folders deepest first, all relative to the stage.
$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('; Generated by tools\build-installer.ps1 from the published stage. Do not edit.')
Get-ChildItem -LiteralPath $StageDir -File -Recurse | Sort-Object FullName | ForEach-Object {
    $relative = $_.FullName.Substring($StageDir.Length).TrimStart('\')
    $lines.Add('Delete "$INSTDIR\' + $relative + '"')
}
Get-ChildItem -LiteralPath $StageDir -Directory -Recurse |
    Sort-Object { $_.FullName.Split('\').Count }, FullName -Descending | ForEach-Object {
        $relative = $_.FullName.Substring($StageDir.Length).TrimStart('\')
        $lines.Add('RMDir "$INSTDIR\' + $relative + '"')
    }
$includePath = Join-Path $generatedDir 'shipped-files.nsh'
[IO.File]::WriteAllLines($includePath, $lines, [Text.UTF8Encoding]::new($true))

$fileCount = (Get-ChildItem -LiteralPath $StageDir -File -Recurse | Measure-Object).Count

# Both passes read the same defines.
$commonDefines = @(
    "/DVERSION=$version",
    "/DVERSION4=$version4",
    "/DSTAGE_DIR=$StageDir",
    "/DGENERATED_DIR=$generatedDir",
    "/DICON_FILE=$icon",
    "/DRUNTIME_MIN=$runtimeMin",
    "/DRUNTIME_SCRIPT=$runtimeScript"
)

if ($UninstallerOnly) {
    # Pass 1: compile the generator, run it and keep the uninstaller it writes. The release signs that file, then
    # runs this script again with -SignedUninstaller. The generator is deleted.
    $uninstallerDir = Join-Path $OutputDir 'uninstaller'
    if (Test-Path -LiteralPath $uninstallerDir) { Remove-Item -LiteralPath $uninstallerDir -Recurse -Force }
    New-Item -ItemType Directory -Path $uninstallerDir -Force | Out-Null
    $uninstallerPath = Join-Path $uninstallerDir 'Uninstall.exe'
    $generator = Join-Path $generatedDir 'uninstaller-generator.exe'
    if (Test-Path -LiteralPath $generator) { Remove-Item -LiteralPath $generator -Force }
    Write-Host "App Packager Desktop $version uninstaller <- $StageDir ($fileCount files)"
    & $MakeNsis /V2 /INPUTCHARSET UTF8 @commonDefines "/DBUILD_UNINSTALLER" "/DUNINSTALLER_FILE=$uninstallerPath" "/DOUT_FILE=$generator" $script
    if ($LASTEXITCODE -ne 0) { throw "makensis failed with exit code $LASTEXITCODE (uninstaller generator)" }
    $run = Start-Process -FilePath $generator -ArgumentList '/S' -Wait -PassThru
    if ($run.ExitCode -ne 0) { throw "The uninstaller generator ended with exit code $($run.ExitCode)." }
    Remove-Item -LiteralPath $generator -Force
    if (-not (Test-Path -LiteralPath $uninstallerPath)) { throw "The generator ran but $uninstallerPath is missing." }
    $uninstaller = Get-Item -LiteralPath $uninstallerPath
    Write-Host ("uninstaller: {0} ({1:N0} KB)" -f $uninstaller.FullName, ($uninstaller.Length / 1KB))
    $uninstallerPath
    return
}

Write-Host "App Packager Desktop $version installer <- $StageDir ($fileCount files)"
$signedDefine = @()
if ($SignedUninstaller) {
    if (-not (Test-Path -LiteralPath $SignedUninstaller)) { throw "Signed uninstaller not found: $SignedUninstaller" }
    $signedDefine = @("/DSIGNED_UNINSTALLER=$((Resolve-Path -LiteralPath $SignedUninstaller).Path)")
    Write-Host "uninstaller: $SignedUninstaller (built before and signed)"
}
else {
    Write-Warning 'No signed uninstaller given; the installer writes its own, unsigned uninstaller.'
}

& $MakeNsis /V2 /INPUTCHARSET UTF8 @commonDefines @signedDefine "/DOUT_FILE=$outFile" $script
if ($LASTEXITCODE -ne 0) { throw "makensis failed with exit code $LASTEXITCODE" }
if (-not (Test-Path -LiteralPath $outFile)) { throw "makensis reported success but $outFile is missing." }

$item = Get-Item -LiteralPath $outFile
Write-Host ("installer  : {0} ({1:N1} MB)" -f $item.Name, ($item.Length / 1MB))
$outFile
